-- A revocation counter per account.
--
-- A refresh cookie is good for a week and nothing could withdraw it. Somebody who
-- had taken over a session therefore kept it for up to seven days *after* the
-- owner noticed and changed their password — which is the one action a victim
-- takes expecting it to end the intrusion.
--
-- This column is the revocation list. Every access and refresh token carries the
-- value it was minted against as a `tv` claim, and `AuthService.refresh` refuses
-- any token whose claim no longer matches the row. Changing or resetting a
-- password increments it, so every other session dies at its next refresh —
-- within the access token's fifteen minutes rather than within a week. Changing a
-- password from the account page mints a fresh session in the same response, so
-- the session doing the changing survives and only the others die.
--
-- A counter rather than a `password_changed_at` timestamp, which was the obvious
-- first attempt and is subtly wrong: a JWT's `iat` has one-second precision, so a
-- password change that completed in the same second as the session was minted
-- revoked that very session and signed the user out of the page they were
-- standing on. A counter has no precision to lose.
--
-- DEFAULT 0 and NOT NULL, matching the absent claim on tokens issued before this
-- migration: existing sessions are read as version 0 and keep working.
--
-- !! SYNTAX: MariaDB 10.4 (what XAMPP ships). See the note at the top of V5.
-- ============================================================================

ALTER TABLE users ADD COLUMN token_version INT NOT NULL DEFAULT 0 AFTER password;
